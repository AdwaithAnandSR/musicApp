import mongoose from "mongoose";

const musicSchema = mongoose.Schema({
    title: {
        type: String,
        required: true,
        index: true
    },

    url: {
        type: String,
        required: true
    },

    cover: String,

    duration: Number,

    artist: {
        type: String,
        default: "Unknown"
    },

    ytId: String,

    synced: {
        type: Boolean,
        default: false
    },

    lyrics: [
        {
            start: Number,
            end: Number,
            line: String
        }
    ],

    lang: String,

    isLyricsAutoGenerated: {
        type: Boolean,
        default: false
    },

    lyricsAsText: [{ type: String }],

    stableRandom: Number,

    // AI enrichment
    ai: {
        processed: {
            type: Boolean,
            default: false,
            index: true
        },

        processing: {
            type: Boolean,
            default: false
        },

        // Web search cache
        webSearched: {
            type: Boolean,
            default: false
        },

        webSearchedAt: Date,

        webSources: [
            {
                title: String,
                url: String,
                snippet: String
            }
        ],

        // AI analysis
        processedAt: Date,

        language: String,

        moods: [String],

        themes: [String],

        genres: [String],

        situations: [String],

        energy: String,

        description: String,

        searchText: String,

        // Gemini embedding
        embedding: [Number],

        error: String
    },

    createdAt: {
        type: Date,
        default: Date.now
    }
});

musicSchema.index({ createdAt: -1 });

// Full-text search
musicSchema.index(
    {
        title: "text",
        artist: "text",
        lyricsAsText: "text"
    },
    {
        weights: {
            title: 10,
            artist: 5,
            lyricsAsText: 1
        },
        name: "music_text_search"
    }
);

export default mongoose.model("music", musicSchema);
